@app.get("/real/forecast")
def real_forecast(horizon: str = "J+1", start: str = "2024-04-01", days: int = 3):
    """Stored out-of-sample test forecasts vs measured production (test period Dec 2023 - May 2024)."""
    try:
        f = pd.read_csv("data/validation/real_test_forecasts.csv.gz", parse_dates=["timestamp"])
    except FileNotFoundError:
        raise HTTPException(503, "Run scripts/12_real_benchmark.py first.")
    f = f[(f.horizon == horizon) & (f.timestamp >= start) & (f.timestamp < pd.Timestamp(start) + pd.Timedelta(days=days))]
    if f.empty:
        raise HTTPException(404, "No rows for that horizon/period (test period is 2023-12-01..2024-05-31).")
    f = f.assign(timestamp=f.timestamp.astype(str), data_source="MEASURED_REAL_ENSTAB")
    return f.drop(columns=["issue_time"]).to_dict("records")


