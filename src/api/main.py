DATA_PATH = Path("data/processed/training_dataset_15min_real_reference_sample.csv")
TARGET_COL = "pv_production_mw_reference"
MODEL_VERSION = "pestgm-reference-lightgbm-0.3"

if not DATA_PATH.exists():
    DATA_PATH = Path("data/processed/training_dataset_15min_sample.csv")
    TARGET_COL = "pv_production_mw_proxy"
    MODEL_VERSION = "demo-physics-lightgbm-0.2"

_CACHE: dict = {}


def _load() -> pd.DataFrame:
    if not DATA_PATH.exists():
        raise HTTPException(status_code=503, detail=f"{DATA_PATH} not built yet - run scripts/04 or 10.")
    if "df" not in _CACHE:
        d = pd.read_csv(DATA_PATH, parse_dates=["timestamp"])
        if "capacity_mw" not in d.columns and "installed_capacity_mw" in d.columns:
            d["capacity_mw"] = d["installed_capacity_mw"]
        d[NH.FCOL] = NH.hybrid_forecast_mw(d)
        _CACHE["df"] = d
    return _CACHE["df"]


def _levels(df: pd.DataFrame) -> dict:
    """Bottom-up levels carrying BOTH the model forecast and the reference/target column."""
    f = reconcile_all_levels(df, NH.FCOL)
    r = reconcile_all_levels(df, TARGET_COL)
    keys = {"district": ["timestamp", "district_id"], "governorate": ["timestamp", "governorate"], "national": ["timestamp"]}
    return {k: f[k].merge(r[k][keys[k] + [TARGET_COL]], on=keys[k]) for k in f}


class ForecastPoint(BaseModel):
    forecast_issue_time: str
    target_timestamp: str
    horizon: str
    spatial_level: str
    entity: str
    forecast_mw: float
    p10_mw: float | None = None
    p50_mw: float | None = None
    p90_mw: float | None = None
    reference_mw: float | None = None
    forecast_method: str = "calibrated-physics hybrid (ENSTAB-calibrated)"
    model_version: str
    data_source: str
    forecast_status: str
    generation_time: str


class ForecastRequest(BaseModel):
    spatial_level: str  # district | governorate | national
    entity: str
    horizon: str = "intraday_15min"


def _data_source_label(df: pd.DataFrame) -> str:
    if df is not None and "_src" in df.attrs:
        return df.attrs["_src"]
    col = "production_source" if TARGET_COL == "pv_production_mw_reference" else "pv_production_source"
    return df[col].iloc[0] if col in df.columns and len(df) else "UNKNOWN"


def _forecast_status_label(df: pd.DataFrame) -> str:
    label = _data_source_label(df)
    return label if label != "UNKNOWN" else "SIMULATED"


@app.get("/health")
def health():
    return {"status": "ok", "data_mode": get_data_mode().value, "time": datetime.now(timezone.utc).isoformat()}


@app.get("/districts")
def districts():
    df = _load()
    out = df.drop_duplicates("district_id")[["district_id", "district", "governorate", "latitude", "longitude"]]
    return out.to_dict(orient="records")


@app.get("/capacity")
def capacity(district_id: str | None = None):
    df = _load()
    if district_id:
        df = df[df["district_id"] == district_id]
        if df.empty:
            raise HTTPException(404, f"Unknown district_id {district_id}")
    latest = df.sort_values("timestamp").groupby("district_id").tail(1)
    
    cap_col = "capacity_mw" if "capacity_mw" in df.columns else "installed_capacity_mw"
    src_col = "capacity_source" if "capacity_source" in df.columns else "fleet_snapshot_source"
    
    res = latest[["district_id", "district", "governorate", "timestamp", cap_col, src_col]].copy()
    res = res.rename(columns={cap_col: "capacity_mw", src_col: "capacity_source"})
    return res.to_dict(orient="records")


def _points_from_series(sub: pd.DataFrame, level: str, entity: str, now: str) -> list[dict]:
    sub.attrs["_src"] = _data_source_label(_load())
    return [
        ForecastPoint(
            forecast_issue_time=now, target_timestamp=row["timestamp"].isoformat() if hasattr(row["timestamp"], "isoformat") else str(row["timestamp"]),
            horizon="intraday_15min", spatial_level=level, entity=entity,
            forecast_mw=float(row[NH.FCOL]), reference_mw=float(row[TARGET_COL]),
            model_version=MODEL_VERSION, data_source=_data_source_label(sub),
            forecast_status=_forecast_status_label(sub), generation_time=now,
        ).model_dump()
        for _, row in sub.iterrows()
    ]


@app.get("/forecast/district/{district_id}")
def forecast_district(district_id: str):
    df = _load()
    g = df[df["district_id"] == district_id]
    if g.empty:
        raise HTTPException(404, f"Unknown district_id {district_id}")
    now = datetime.now(timezone.utc).isoformat()
    return _points_from_series(_levels(g)["district"].sort_values("timestamp"), "district", district_id, now)


@app.get("/forecast/governorate/{governorate}")
def forecast_governorate(governorate: str):
    df = _load()
    g = df[df["governorate"] == governorate]
    if g.empty:
        raise HTTPException(404, f"Unknown governorate {governorate}")
    levels = _levels(g)
    now = datetime.now(timezone.utc).isoformat()
    return _points_from_series(levels["governorate"], "governorate", governorate, now)


@app.get("/forecast/national")
def forecast_national():
    df = _load()
    levels = _levels(df)
    now = datetime.now(timezone.utc).isoformat()
    return _points_from_series(levels["national"], "national", "TUNISIA", now)


@app.post("/forecast")
def post_forecast(req: ForecastRequest):
    """Generic forecast endpoint: dispatches to the district/governorate/national
    getters above based on the request body (CDC-required POST /forecast)."""
    if req.spatial_level == "district":
        return forecast_district(req.entity)
    if req.spatial_level == "governorate":
        return forecast_governorate(req.entity)
    if req.spatial_level == "national":
        return forecast_national()
    raise HTTPException(400, "spatial_level must be one of district|governorate|national")


@app.get("/uncertainty")
def uncertainty(district_id: str, horizon: str = "J+1"):
    """P10/P50/P90 for a district: model forecast with an interval TRANSFERRED from the
    ENSTAB conformal-calibrated ratios (see src/forecasting/national_hybrid.py)."""
    df = _load()
    g = df[df["district_id"] == district_id].sort_values("timestamp")
    if g.empty:
        raise HTTPException(404, f"Unknown district_id {district_id}")
    iv = NH.add_interval(g[NH.FCOL], g["capacity_mw"], horizon)
    out = pd.concat([g[["timestamp"]], iv], axis=1)
    out["pv_production_mw_forecast"] = out["p50_mw"]
    return out.to_dict(orient="records")


@app.get("/errors")
def errors(district_id: str):
    """Forecast-vs-actual error using persistence as the stand-in 'forecast'
    (DEMO_ONLY - a genuine ML-forecast-vs-actual log requires the scripts/05-07
    pipeline artifacts; this endpoint demonstrates the schema and computation)."""
    df = _load()
    g = df[df["district_id"] == district_id].sort_values("timestamp").copy()
    if g.empty:
        raise HTTPException(404, f"Unknown district_id {district_id}")
        
    cap_col = "capacity_mw" if "capacity_mw" in g.columns else "installed_capacity_mw"
        
    g["persistence_forecast_mw"] = g[TARGET_COL].shift(1)
    g = g.dropna(subset=["persistence_forecast_mw"])
    m = evaluate(g[TARGET_COL], g["persistence_forecast_mw"], g[cap_col])
    return {"district_id": district_id, "baseline": "persistence", "metrics": m}


@app.get("/anomalies")
def anomalies(district_id: str | None = None):
    df = _load()
    if district_id:
        df = df[df["district_id"] == district_id]
        if df.empty:
            raise HTTPException(404, f"Unknown district_id {district_id}")
    flags = anomaly_flags(df, production_col=TARGET_COL)
    flagged = flags[flags["physical_anomaly_flag"]]
    return {
        "n_checked": len(flags),
        "n_flagged": len(flagged),
        "pct_flagged": round(100 * len(flagged) / max(len(flags), 1), 3),
        "sample_flagged_rows": flagged.head(20).to_dict(orient="records"),
    }


